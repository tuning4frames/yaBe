CHORDS = {"x": (0, 3), "y": (1, 2)}

def lanes_of(c):
    if c in CHORDS:
        return CHORDS[c]
    if c.isdigit():
        return (int(c),)
    return ()

def level(i):
    return LEVELS[max(0, min(len(LEVELS) - 1, i))]

def count():
    return len(LEVELS)

def main_bars(lv):
    return len(lv["song"])

def bars(lv):
    return INTRO_BARS + main_bars(lv) + OUTRO_BARS

def pattern(lv, i):
    c = lv["song"][i]
    return "." * 16 if c == "." else BANKS[lv["bank"]][int(c)]

def star_string(n):
    return "*" * n + "-" * (5 - n)
